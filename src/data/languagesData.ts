/**
 * Função utilitária modular: obtém o quiz dedicado da linguagem
 * ou gera dinamicamente questões estruturadas de fundamentos
 * para garantir que 100% de qualquer linguagem atual ou futura possua testes práticos.
 */
export function getLanguageQuiz(lang: LanguageItem): LanguageQuizQuestion[] {
  if (lang.quiz && lang.quiz.length > 0) {
    return lang.quiz;
  }

  return [
    {
      id: `${lang.id}-foundations-1`,
      question: `Qual é o propósito e domínio mais comum de aplicação para ${lang.name}?`,
      options: [
        lang.popularUses.split(',')[0]?.trim() || 'Desenvolvimento especializado de software',
        'Estilização de panfletos impressos físicos',
        'Emulação exclusiva de hardware legado analógico',
        'Substituição universal de protocolos de bios físicos',
      ],
      correctAnswerIndex: 0,
      explanation: `${lang.name} destaca-se primordialmente no seguinte cenário de uso: ${lang.popularUses}.`,
      difficulty: 'iniciante',
    },
    {
      id: `${lang.id}-foundations-2`,
      question: `Qual das extensões abaixo está associada a arquivos de código de ${lang.name}?`,
      options: [
        lang.extensions[0] || '.txt',
        '.xyz_backup',
        '.raw_sample',
        '.temp_buffer',
      ],
      correctAnswerIndex: 0,
      explanation: `Arquivos desenvolvidos em ${lang.name} utilizam convencionalmente as extensões: ${lang.extensions.join(', ')}.`,
      difficulty: 'iniciante',
    },
    {
      id: `${lang.id}-foundations-3`,
      question: `Como ${lang.name} é categorizada formalmente no ecossistema técnico?`,
      options: [
        lang.description.slice(0, 90) + (lang.description.length > 90 ? '...' : ''),
        'Microcontrolador de firmware estático não programável',
        'Protocolo de conexão serial cabeada antiga',
        'Algoritmo exclusivo de compressão em lote',
      ],
      correctAnswerIndex: 0,
      explanation: lang.description,
      difficulty: 'iniciante',
    },
  ];
}
